/** Build the standard `npx skills add` CLI command for installing this skill. */
export function featuredSkillInstallCommand(item: Pick<FeaturedSkill, 'source' | 'skillId'>): string {
  return `npx skills add ${item.source} --skill ${item.skillId}`
}

/** Format a skills.sh All Time install count compactly (e.g. `4.5M`, `925K`). */
export function formatSkillInstalls(installs: number): string {
  if (!Number.isFinite(installs) || installs <= 0) return ''
  if (installs >= 1_000_000) return `${(installs / 1_000_000).toFixed(1).replace(/\.0$/, '')}M`
  if (installs >= 1_000) return `${installs >= 100_000 ? Math.round(installs / 1_000) : (installs / 1_000).toFixed(1).replace(/\.0$/, '')}K`
  return String(Math.floor(installs))
}

/** Look up a curated skill by exact `id` (`owner/repo/skillId`) or case-insensitive `skillId`/`name`. */
export function findFeaturedSkillById(target: string): FeaturedSkill | undefined {
  const needle = target.trim().toLowerCase()
  if (needle === '') return undefined
  const exact = FEATURED_SKILLS.find(item => item.id.toLowerCase() === needle)
  if (exact !== undefined) return exact
  return FEATURED_SKILLS.find(item => item.skillId.toLowerCase() === needle || item.name.toLowerCase() === needle)
}

/** Whether a curated skill satisfies the official filter pill. */
export function matchesFeaturedSkillOrigin(item: FeaturedSkill, filter: FeaturedSkillOriginFilter): boolean {
  return filter === 'all' || item.official
}

/** Match a curated skill against category, official filter, and bilingual search query. */
export function matchesFeaturedSkill(
  item: FeaturedSkill,
  rawQuery: string,
  category: FeaturedSkillCategory | 'all',
  originFilter: FeaturedSkillOriginFilter = 'all',
): boolean {
  if (category !== 'all' && item.category !== category) return false
  if (!matchesFeaturedSkillOrigin(item, originFilter)) return false
  const query = rawQuery.trim().toLocaleLowerCase()
  if (query === '') return true
  const haystack = [
    item.name,
    item.skillId,
    item.source,
    item.path,
    item.category,
    item.descriptionZh,
    item.descriptionEn,
    ...(item.keywords ?? []),
  ].join(' ').toLocaleLowerCase()
  const terms = query.split(/\s+/).filter(Boolean)
  return terms.every(term => haystack.includes(term))
}

/** Minimal shape of an installed local skill needed for featured matching. */
export interface InstalledSkillLike {
  readonly name: string
  readonly source?: string
  readonly sourceDirectory?: string
  readonly provider?: string
}

/** Match a curated skill against the session's currently available skills. */
export function findInstalledFeaturedSkill<T extends InstalledSkillLike>(
  item: Pick<FeaturedSkill, 'skillId' | 'name'>,
  installed: readonly T[],
): T | null {
  const idNeedle = item.skillId.toLowerCase()
  const nameNeedle = item.name.toLowerCase()
  for (const skill of installed) {
    const current = skill.name.trim().toLowerCase()
    if (current === idNeedle || current === nameNeedle) return skill
  }
  return null
}

/**
 * Pure check whether an installed skill directory path sits strictly inside a
 * user/project `.dsh/skills/` or `.agents/skills/` root and is safe to offer
 * for deletion (never bundled, never `node_modules`, never the skills root).
 */
export function isDeletableSkillPath(sourcePath: string | undefined): boolean {
  if (typeof sourcePath !== 'string') return false
  const trimmed = sourcePath.trim()
  if (trimmed === '' || trimmed.length > 4096 || /[\u0000-\u001f]/.test(trimmed)) return false
  const normalized = trimmed.replace(/\\/g, '/').replace(/\/+$/, '')
  const isAbs = normalized.startsWith('/') || /^[A-Za-z]:\//.test(normalized)
  if (!isAbs) return false
  const segments = normalized.split('/').filter(Boolean)
  if (segments.length < 3) return false
  if (segments.some(seg => seg === '.' || seg === '..')) return false
  const lower = segments.map(seg => seg.toLowerCase())
  if (lower.includes('node_modules') || lower.some(seg => seg.endsWith('.asar'))) return false
  for (let i = 0; i < lower.length - 2; i += 1) {
    if ((lower[i] === '.dsh' || lower[i] === '.agents') && lower[i + 1] === 'skills') {
      return i + 2 < lower.length
    }
  }
  return false
}
