/** Build the GitHub URL pointing directly to this skill directory (or repo root). */
export function featuredSkillGithubUrl(item: Pick<FeaturedSkill, 'source' | 'path'>): string {
  if (item.path === '') return `https://github.com/${item.source}`
  const encodedPath = item.path.split('/').map(segment => encodeURIComponent(segment)).join('/')
  return `https://github.com/${item.source}/tree/HEAD/${encodedPath}`
}

